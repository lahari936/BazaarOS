const lang = (l) => (M[l] ? l : 'en-IN');
const fmt = (v) => (typeof v === 'number' ? String(Math.round(v * 100) / 100) : v ?? '');

export const msg = (language, key, vars = {}) => (M[lang(language)][key] || key).replace(/\{(\w+)\}/g, (_, k) => fmt(vars[k]));
export const unitName = (language, unit) => UNITS[lang(language)][unit] || unit || '';
export const periodName = (language, p) => PERIOD[lang(language)][p] || p;
/** Rupee amounts are spoken rounded to whole rupees. */
export const rupees = (n) => Math.round(Math.abs(n || 0));
